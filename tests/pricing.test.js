const { calcTotal, maxTickets } = require('../js/pricing');
test('two tickets cost 724', function () { assertEq(calcTotal(2), 724); });
test('one ticket costs 362', function () { assertEq(calcTotal(1), 362); });
test('regular customers may buy up to 8', function () { assertEq(maxTickets(), 8); });
test('member gets 20% off the ticket only', function () { assertEq(calcTotal(2, true), 584); });
test('members may buy up to 4', function () { assertEq(maxTickets(true), 4); });
test('member over quota is invalid', function () { assertEq(calcTotal(5, true), null); });
test('zero tickets is invalid', function () { assertEq(calcTotal(0), null); });
test('regular over quota is invalid', function () { assertEq(calcTotal(9), null); });
test('members may buy up to 6', function () { assertEq(maxTickets(true), 6); });
